def seed():
    db = SessionLocal()
    provinces_created = 0
    cities_created = 0

    try:
        for province_name, city_names in PROVINCES_AND_CITIES.items():
            province = db.query(Province).filter(Province.name == province_name).first()
            if province is None:
                province = Province(name=province_name)
                db.add(province)
                db.flush()  # get province.id for the cities below
                provinces_created += 1

            for city_name in city_names:
                exists = (
                    db.query(City)
                    .filter(City.name == city_name, City.province_id == province.id)
                    .first()
                )
                if exists is None:
                    db.add(City(name=city_name, province_id=province.id))
                    cities_created += 1

        db.commit()
        print(f"Done - {provinces_created} province(s) and {cities_created} city(ies) added.")
        total_provinces = db.query(Province).count()
        total_cities = db.query(City).count()
        print(f"Totals in DB now: {total_provinces} provinces, {total_cities} cities.")
    finally:
        db.close()


if __name__ == "__main__":
    seed()
